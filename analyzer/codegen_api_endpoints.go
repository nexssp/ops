package analyzer

import (
	"bytes"
	"encoding/json"
	"fmt"
	"strings"
)

// generateEndpointsFile emits _gen/api/endpoints.ts.
//
// Each public non-streaming non-raw action becomes one typed method. Three
// transport shapes are recognised:
//
//   - JSON      : default — JSON body in, JSON body out
//   - Multipart : any request field carries a `form:` tag on a []byte field
//   - Blob      : response type is []byte
func generateEndpointsFile(report *Report, tsStructs map[string]StructDefinition, colliding map[string]bool) []byte {
	var buf bytes.Buffer
	buf.WriteString("// ⚠️ DO NOT EDIT — Auto-generated by nexssp/ops\n")
	buf.WriteString("import { _fetcher, _fetcherBlob, _fetcherMultipart, resolvePath, resolvePathOnly } from './client';\n")
	buf.WriteString("import * as Types from './types';\n\n")

	buf.WriteString(`export interface FieldMeta {
  name: string;
  key: string;
  type: string;
  required: boolean;
  validation?: string;
  raw_tags?: string;
  multipart?: boolean;
}

export interface EndpointMeta {
  name: string;
  method: string;
  path: string;
  streaming?: boolean;
  raw?: boolean;
  multipart?: boolean;
  blob?: boolean;
  reqFields?: FieldMeta[];
}

export const endpointMeta: Record<string, EndpointMeta> = {
`)
	for _, act := range report.Actions {
		if act.Scope != "public" || act.Path == "" {
			continue
		}
		mName := toCamelCase(act.Name)
		fieldsJSON, _ := json.Marshal(act.ReqFields)
		if len(act.ReqFields) == 0 {
			fieldsJSON = []byte("[]")
		}
		extra := ""
		if act.Multipart {
			extra += ", multipart: true"
		}
		if act.BlobResponse {
			extra += ", blob: true"
		}
		fmt.Fprintf(&buf,
			"  %s: { name: %q, method: %q, path: %q, streaming: %v, raw: %v%s, reqFields: %s },\n",
			mName, act.Name, act.Method, act.Path,
			act.Streaming, act.Raw, extra, string(fieldsJSON),
		)
	}
	buf.WriteString("};\n\nexport const api = {\n")

	for _, act := range report.Actions {
		if act.Scope != "public" || act.Path == "" {
			continue
		}
		if act.Streaming || act.Raw {
			continue
		}

		emitEndpointMethod(&buf, act, tsStructs, report.Structs, colliding)
	}

	buf.WriteString("};\n")
	return buf.Bytes()
}

// pathResolverFor returns the client-side URL resolver that matches the HTTP
// method. GET and DELETE carry their payload in the query string; POST, PUT,
// and PATCH carry it in the body. Using resolvePath for a body method would
// duplicate every field into both the URL and the JSON body.
func pathResolverFor(method string) string {
	switch method {
	case "GET", "DELETE":
		return "resolvePath"
	default:
		return "resolvePathOnly"
	}
}

func emitEndpointMethod(
	buf *bytes.Buffer,
	act ActionContract,
	tsStructs, rawStructs map[string]StructDefinition,
	colliding map[string]bool,
) {
	mName := toCamelCase(act.Name)
	resolver := pathResolverFor(act.Method)

	// Blob response short-circuits everything else.
	if act.BlobResponse {
		reqT := formatTSNamespaceType(resolveActionTypeTS(act, true, tsStructs, rawStructs, colliding), tsStructs)
		valCheck := ""
		if sDef, ok := resolveActionStruct(act, true, rawStructs); ok && len(sDef.Fields) > 0 {
			valCheck = fmt.Sprintf("\n    Types.%sSchema.parse(req ?? {});", targetTSName(sDef, colliding))
		}
		if reqT == "void" {
			fmt.Fprintf(buf,
				"  %s: (): Promise<Blob> => {\n    return _fetcherBlob({ method: '%s', path: '%s' });\n  },\n\n",
				mName, act.Method, act.Path,
			)
			return
		}
		if act.Method == "GET" || act.Method == "DELETE" {
			fmt.Fprintf(buf,
				"  %s: (req?: %s): Promise<Blob> => {%s\n    return _fetcherBlob({ method: '%s', path: %s('%s', req) });\n  },\n\n",
				mName, reqT, valCheck, act.Method, resolver, act.Path,
			)
			return
		}
		fmt.Fprintf(buf,
			"  %s: (req: %s): Promise<Blob> => {%s\n    return _fetcherBlob({ method: '%s', path: %s('%s', req), body: req });\n  },\n\n",
			mName, reqT, valCheck, act.Method, resolver, act.Path,
		)
		return
	}

	// Multipart.
	if act.Multipart {
		reqT := formatTSNamespaceType(resolveActionTypeTS(act, true, tsStructs, rawStructs, colliding), tsStructs)
		resT := formatTSNamespaceType(resolveActionTypeTS(act, false, tsStructs, rawStructs, colliding), tsStructs)

		sDef, hasStruct := resolveActionStruct(act, true, rawStructs)
		tsReqT := lastSegment(act.ReqTypeName)
		if hasStruct {
			tsReqT = targetTSName(sDef, colliding)
		}

		fmt.Fprintf(buf, "  %s: (req: %s): Promise<%s> => {\n", mName, reqT, resT)
		fmt.Fprintf(buf, "    const fd = new FormData();\n")

		if hasStruct {
			for _, f := range sDef.Fields {
				if f.Multipart {
					fmt.Fprintf(buf, "    fd.append(%q, req.%s as unknown as Blob);\n", f.Key, f.Key)
				} else {
					fmt.Fprintf(buf, "    fd.append(%q, String(req.%s ?? ''));\n", f.Key, f.Key)
				}
			}
		}
		_ = tsReqT

		fmt.Fprintf(buf, "    return _fetcherMultipart({ method: '%s', path: %s('%s', req), body: fd });\n", act.Method, resolver, act.Path)
		fmt.Fprintf(buf, "  },\n\n")
		return
	}

	// Plain JSON — the existing path.
	rawReqT := resolveActionTypeTS(act, true, tsStructs, rawStructs, colliding)
	rawResT := resolveActionTypeTS(act, false, tsStructs, rawStructs, colliding)

	reqT := formatTSNamespaceType(rawReqT, tsStructs)
	resT := formatTSNamespaceType(rawResT, tsStructs)

	valCheck := ""
	if sDef, ok := resolveActionStruct(act, true, rawStructs); ok && len(sDef.Fields) > 0 {
		valCheck = fmt.Sprintf("\n    Types.%sSchema.parse(req ?? {});", targetTSName(sDef, colliding))
	}

	if reqT == "void" {
		fmt.Fprintf(buf,
			"  %s: (): Promise<%s> => {\n    return _fetcher({ method: '%s', path: '%s' });\n  },\n\n",
			mName, resT, act.Method, act.Path,
		)
		return
	}

	if act.Method == "GET" || act.Method == "DELETE" {
		fmt.Fprintf(buf,
			"  %s: (req?: %s): Promise<%s> => {%s\n    return _fetcher({ method: '%s', path: %s('%s', req) });\n  },\n\n",
			mName, reqT, resT, valCheck, act.Method, resolver, act.Path,
		)
		return
	}

	fmt.Fprintf(buf,
		"  %s: (req: %s): Promise<%s> => {%s\n    return _fetcher({ method: '%s', path: %s('%s', req), body: req });\n  },\n\n",
		mName, reqT, resT, valCheck, act.Method, resolver, act.Path,
	)
}

func formatTSNamespaceType(t string, tsStructs map[string]StructDefinition) string {
	if t == "" || t == "void" || t == "unknown" {
		return "void"
	}
	switch t {
	case "string", "number", "boolean", "IsoDateString":
		return t
	}
	if strings.HasPrefix(t, "Record<") || strings.HasSuffix(t, "[]") || strings.Contains(t, "|") {
		return t
	}
	if sDef, ok := tsStructs[t]; ok {
		// Structs with zero fields are filtered out of types.ts. Referring
		// to Types.X for them produces a dangling reference in the emitted
		// endpoint methods. Treat as void so the method has no typed arg.
		if len(sDef.Fields) == 0 {
			return "void"
		}
		return "Types." + t
	}
	return "Record<string, unknown>"
}
