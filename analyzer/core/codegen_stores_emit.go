func emitEntityStore(c StoreCluster, report *Report, colliding map[string]bool) []byte {
	var b bytes.Buffer

	fmt.Fprintf(&b, "// ⚠️ DO NOT EDIT — generated by nexssp/ops\n")
	fmt.Fprintf(&b, "// Resource: %s\n", c.Noun)
	fmt.Fprintf(&b, "// Actions:\n")
	for _, a := range []*ActionContract{c.List, c.Get, c.Create, c.Update, c.Delete} {
		if a != nil {
			fmt.Fprintf(&b, "//   - %s (%s %s)\n", a.Name, a.Method, a.Path)
		}
	}
	fmt.Fprintf(&b, "\n")

	fmt.Fprintf(&b, "import { api } from '#lib/_gen/api/index.js';\n")
	fmt.Fprintf(&b, "import * as Types from '#lib/_gen/api/types.js';\n")
	fmt.Fprintf(&b, "import { createEntityStore } from '#lib/_gen/stores/runtime/index.js';\n\n")

	fmt.Fprintf(&b, "export const %s = createEntityStore({\n", c.Noun)
	fmt.Fprintf(&b, "  resource: %q,\n", c.Noun)
	fmt.Fprintf(&b, "  idField:  %q,\n", c.IDField)
	fmt.Fprintf(&b, "  api: {\n")
	if c.List != nil {
		fmt.Fprintf(&b, "    list:   api.%s,\n", toCamelCase(c.List.Name))
	}
	if c.Get != nil {
		fmt.Fprintf(&b, "    get:    api.%s,\n", toCamelCase(c.Get.Name))
	}
	if c.Create != nil {
		fmt.Fprintf(&b, "    create: api.%s,\n", toCamelCase(c.Create.Name))
	}
	if c.Update != nil {
		fmt.Fprintf(&b, "    update: api.%s,\n", toCamelCase(c.Update.Name))
	}
	if c.Delete != nil {
		fmt.Fprintf(&b, "    remove: api.%s,\n", toCamelCase(c.Delete.Name))
	}
	fmt.Fprintf(&b, "  },\n")

	fmt.Fprintf(&b, "  schemas: {\n")
	if c.Get != nil {
		if sDef, ok := resolveActionStruct(*c.Get, true, report.Structs); ok {
			fmt.Fprintf(&b, "    get:    Types.%sSchema,\n", targetTSName(sDef, colliding))
		}
	}
	if c.Create != nil {
		if sDef, ok := resolveActionStruct(*c.Create, true, report.Structs); ok {
			fmt.Fprintf(&b, "    create: Types.%sSchema,\n", targetTSName(sDef, colliding))
		}
	}
	if c.Update != nil {
		if sDef, ok := resolveActionStruct(*c.Update, true, report.Structs); ok {
			fmt.Fprintf(&b, "    update: Types.%sSchema,\n", targetTSName(sDef, colliding))
		}
	}
	fmt.Fprintf(&b, "  },\n")
	fmt.Fprintf(&b, "});\n\n")

	// No type-alias re-exports here. Every DTO shape already lives in
	// _gen/api/types.ts and is exported through the api barrel; re-exporting
	// from the store barrel would create ambiguous re-exports when both
	// merge in _gen/index.ts. Consumers import the DTO type directly from
	// #lib/_gen/api when they need it.
	return b.Bytes()
}

func emitFormStore(act ActionContract, report *Report) []byte {
	var b bytes.Buffer
	slug := actionSlug(act.Name)
	camel := toCamelCase(act.Name)

	sDef, hasStruct := resolveActionStruct(act, true, report.Structs)

	tsReqT := lastSegment(act.ReqTypeName)
	if hasStruct {
		tsReqT = targetTSName(sDef, nil)
	}

	// Bail out before writing anything that would be invalid TypeScript.
	// isFormAction should have filtered these already; this guard exists
	// so a future change to that filter cannot silently produce broken
	// output.
	switch tsReqT {
	case "", "struct{}", "struct{...}", "void", "any":
		fmt.Fprintf(&b, "// ⚠️ DO NOT EDIT — generated by nexssp/ops\n")
		fmt.Fprintf(&b, "// Form: %s (%s %s)\n", act.Name, act.Method, act.Path)
		fmt.Fprintf(&b, "//\n")
		fmt.Fprintf(&b, "// Skipped: request type %q is not a named struct.\n", act.ReqTypeName)
		fmt.Fprintf(&b, "// Call api.%s() directly.\n", camel)
		return b.Bytes()
	}

	fmt.Fprintf(&b, "// ⚠️ DO NOT EDIT — generated by nexssp/ops\n")
	fmt.Fprintf(&b, "// Form: %s (%s %s)\n\n", act.Name, act.Method, act.Path)
	fmt.Fprintf(&b, "import { api } from '#lib/_gen/api/index.js';\n")
	fmt.Fprintf(&b, "import * as Types from '#lib/_gen/api/types.js';\n")
	fmt.Fprintf(&b, "import { createFormStore } from '#lib/_gen/stores/runtime/index.js';\n\n")

	fmt.Fprintf(&b, "const initial%s: Types.%s = {\n", toPascalCase(slug), tsReqT)
	if hasStruct {
		for _, f := range sDef.Fields {
			if !f.Required {
				continue
			}
			fmt.Fprintf(&b, "  %s: %s,\n", f.Key, initialValue(f, report, make(map[string]bool)))
		}
	}
	fmt.Fprintf(&b, "};\n\n")

	fmt.Fprintf(&b, "export const %sForm = createFormStore({\n", camel)
	fmt.Fprintf(&b, "  submit:  api.%s,\n", camel)
	fmt.Fprintf(&b, "  schema:  Types.%sSchema,\n", tsReqT)
	fmt.Fprintf(&b, "  initial: initial%s,\n", toPascalCase(slug))
	fmt.Fprintf(&b, "});\n")
	return b.Bytes()
}

func initialValue(f FieldContract, report *Report, seen map[string]bool) string {
	return initialValueForType(f.Type, report, seen)
}

func initialValueForType(typeName string, report *Report, seen map[string]bool) string {
	switch typeName {
	case "string":
		return "''"
	case "number":
		return "0"
	case "boolean":
		return "false"
	case "IsoDateString":
		return "new Date().toISOString()"
	}
	if strings.HasSuffix(typeName, "[]") {
		return "[]"
	}
	if strings.HasPrefix(typeName, "Record<") {
		return "{}"
	}
	if definition, ok := findStructByAny(typeName, nil, report.Structs); ok {
		if seen[definition.Qualified] {
			return "{}"
		}
		seen[definition.Qualified] = true
		fields := make([]string, 0, len(definition.Fields))
		for _, field := range definition.Fields {
			if !field.Required {
				continue
			}
			fields = append(fields, fmt.Sprintf("%s: %s", field.Key, initialValueForType(field.Type, report, seen)))
		}
		delete(seen, definition.Qualified)
		return "{ " + strings.Join(fields, ", ") + " }"
	}
	return "undefined as any"
}

func emitStreamStore(act ActionContract, report *Report) []byte {
	var b bytes.Buffer
	camel := toCamelCase(act.Name)

	typeParam := "unknown"
	importType := ""
	if sDef, ok := resolveActionStruct(act, false, report.Structs); ok {
		ts := targetTSName(sDef, nil)
		if ts != "" && ts != "any" && ts != "void" && ts != "unknown" {
			typeParam = ts
			importType = ts
		}
	}

	fmt.Fprintf(&b, "// ⚠️ DO NOT EDIT — generated by nexssp/ops\n")
	fmt.Fprintf(&b, "// Stream: %s → %s\n\n", act.Name, act.Path)
	fmt.Fprintf(&b, "import { createStreamStore } from '#lib/_gen/stores/runtime/index.js';\n")
	if importType != "" {
		fmt.Fprintf(&b, "import type { %s } from '#lib/_gen/api/types.js';\n", importType)
	}
	fmt.Fprintf(&b, "\n")
	fmt.Fprintf(&b, "export const %s = createStreamStore<%s>({\n", camel, typeParam)
	fmt.Fprintf(&b, "  url: %q,\n", act.Path)
	if ch := streamChannel(act); ch != "" {
		fmt.Fprintf(&b, "  channel: %q,\n", ch)
	}
	fmt.Fprintf(&b, "  cap: 500,\n")
	fmt.Fprintf(&b, "});\n")
	return b.Bytes()
}

func streamChannel(act ActionContract) string {
	for _, t := range act.Transports {
		if t.Kind == "sse" && t.Meta != nil {
			return t.Meta["channel"]
		}
	}
	return ""
}

func emitSystemStores(report *Report) []GeneratedFile {
	perms := map[string]bool{}
	roles := map[string]bool{}
	feats := map[string]bool{}
	for _, a := range report.Actions {
		for _, p := range a.Permissions {
			perms[p] = true
		}
		for _, r := range a.Roles {
			roles[r] = true
		}
		for _, f := range a.Features {
			feats[f] = true
		}
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// ⚠️ DO NOT EDIT — generated by nexssp/ops\n\n")

	writeArr := func(name string, set map[string]bool) {
		keys := make([]string, 0, len(set))
		for k := range set {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		fmt.Fprintf(&b, "export const %s = [", name)
		for i, k := range keys {
			if i > 0 {
				fmt.Fprintf(&b, ", ")
			}
			fmt.Fprintf(&b, "%q", k)
		}
		fmt.Fprintf(&b, "] as const;\n")
		fmt.Fprintf(&b, "export type %s = typeof %s[number];\n\n", singular(name), name)
	}

	writeArr("PERMISSIONS", perms)
	writeArr("ROLES", roles)
	writeArr("FEATURES", feats)

	fmt.Fprintf(&b, "export function hasPermission(granted: readonly string[], p: PERMISSION): boolean {\n")
	fmt.Fprintf(&b, "  return granted.includes('*') || granted.includes(p);\n")
	fmt.Fprintf(&b, "}\n")

	return []GeneratedFile{
		{Path: "_gen/stores/system/permissions.svelte.ts", Content: b.Bytes(), Overwrite: true},
	}
}

func emitStoresIndex(clusters []StoreCluster, report *Report, formNames map[string]bool) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// ⚠️ DO NOT EDIT — generated by nexssp/ops\n\n")

	for _, c := range clusters {
		fmt.Fprintf(&b, "export * from './entities/%s.svelte';\n", c.Noun)
	}

	slugs := make([]string, 0, len(formNames))
	for s := range formNames {
		slugs = append(slugs, s)
	}
	sort.Strings(slugs)
	for _, s := range slugs {
		fmt.Fprintf(&b, "export * from './forms/%s.svelte';\n", s)
	}

	for _, a := range report.Actions {
		if a.Streaming {
			fmt.Fprintf(&b, "export * from './streams/%s.svelte';\n", actionSlug(a.Name))
		}
	}

	fmt.Fprintf(&b, "export * from './system/permissions.svelte';\n")
	return b.Bytes()
}

func singular(s string) string {
	if strings.HasSuffix(s, "S") && len(s) > 1 {
		return s[:len(s)-1]
	}
	return s
}
