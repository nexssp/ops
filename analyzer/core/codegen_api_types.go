package core

import (
	"bytes"
	"fmt"
	"sort"
	"strings"
)

// generateTypesFile emits _gen/api/types.ts — one interface + one Zod schema
// per reachable struct, followed by one const+type pair per extracted enum.
// Reachability is computed from action request/response types plus anything
// explicitly exposed via a type alias or @nexss:expose.
func generateTypesFile(
	report *Report,
	reachable map[string]StructDefinition,
	tsStructs map[string]StructDefinition,
	colliding map[string]bool,
) []byte {
	var buf bytes.Buffer
	buf.WriteString("// ⚠️ DO NOT EDIT — Auto-generated by nexssp/ops\n")
	buf.WriteString("import { z } from 'zod';\n")
	buf.WriteString("import type { IsoDateString } from './client';\n\n")

	keys := make([]string, 0, len(reachable))
	nameCounts := make(map[string]int)
	for k, v := range reachable {
		keys = append(keys, k)
		nameCounts[v.Name]++
	}
	sort.Strings(keys)

	for _, k := range keys {
		sDef := reachable[k]
		if len(sDef.Fields) == 0 {
			continue
		}

		type fieldZod struct {
			expr    string
			unknown []string
		}
		zods := make([]fieldZod, len(sDef.Fields))
		for i, f := range sDef.Fields {
			e, u := mapFieldToZod(f, tsStructs, report.Structs, colliding)
			zods[i] = fieldZod{expr: e, unknown: u}
		}

		tsName := targetTSName(sDef, colliding)
		fmt.Fprintf(&buf, "export interface %s {\n", tsName)
		for i, f := range sDef.Fields {
			if len(zods[i].unknown) > 0 {
				fmt.Fprintf(&buf, "  // ⚠️ unmapped validator rules on %q: %s\n",
					f.Key, strings.Join(zods[i].unknown, ", "))
			}
			opt := "?"
			if f.Required {
				opt = ""
			}
			// Multipart fields are typed as File | Blob so the FormData
			// builder in the endpoint emitter can append without a cast.
			tsType := f.Type
			if f.Multipart {
				tsType = "File | Blob"
			}
			if f.Nullable && !f.Multipart {
				tsType += " | null"
			}
			fmt.Fprintf(&buf, "  %s%s: %s;\n", f.Key, opt, tsType)
		}
		buf.WriteString("}\n\n")

		fmt.Fprintf(&buf, "export const %sSchema = z.object({\n", tsName)
		for i, f := range sDef.Fields {
			expr := zods[i].expr
			if f.Multipart {
				// Client-side, a File/Blob cannot be validated by Zod the
				// same way a string can. Accept any non-null value; the
				// server validates on receive.
				expr = "z.unknown()"
				if !f.Required {
					expr += ".optional().nullable()"
				}
			}
			fmt.Fprintf(&buf, "  %s: %s,\n", f.Key, expr)
		}
		buf.WriteString("});\n\n")

		if !colliding[sDef.Name] && nameCounts[sDef.Name] == 1 && sDef.Name != tsName {
			fmt.Fprintf(&buf,
				"export type %s = %s;\nexport const %sSchema = %sSchema;\n\n",
				sDef.Name, tsName, sDef.Name, tsName)
		}
	}

	// Enums are emitted after structs so any struct-field reference that
	// happens to mention the enum by name resolves during TS compilation.
	emitEnums(&buf, report, tsStructs)

	return buf.Bytes()
}

// emitEnums writes every extracted enum as a TS const+type pair. Enums that
// share a name with a generated struct are skipped to avoid duplicate
// identifiers in the emitted file; the struct's field types would be plain
// string in that case anyway.
func emitEnums(buf *bytes.Buffer, report *Report, tsStructs map[string]StructDefinition) {
	if len(report.Enums) == 0 {
		return
	}

	names := make([]string, 0, len(report.Enums))
	byName := make(map[string]EnumDefinition, len(report.Enums))
	for _, e := range report.Enums {
		if len(e.Values) == 0 {
			continue
		}
		if _, clash := tsStructs[e.TypeName]; clash {
			continue
		}
		names = append(names, e.TypeName)
		byName[e.TypeName] = e
	}
	sort.Strings(names)

	for _, name := range names {
		e := byName[name]
		fmt.Fprintf(buf, "// %s is generated from Go enum %s (%s)\n", name, e.Qualified, e.SourceFile)
		fmt.Fprintf(buf, "export const %s = {\n", name)
		for _, v := range e.Values {
			fmt.Fprintf(buf, "  %s: %q,\n", v.ConstName, v.Value)
		}
		fmt.Fprintf(buf, "} as const;\n")
		fmt.Fprintf(buf, "export type %s = typeof %s[keyof typeof %s];\n\n", name, name, name)
	}
}
