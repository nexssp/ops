// generateEndpointsFile emits _gen/api/endpoints.ts.
//
// Each public non-streaming action becomes one typed method unless it is a raw
// response without a blob contract. Four transport shapes are recognised:
//
//   - JSON      : default — JSON body in, JSON body out
//   - Multipart : request has a form-tagged []byte or transport FormFile field
//   - Blob      : response type is []byte
//   - Raw blob  : a raw response explicitly declared as a blob
func generateEndpointsFile(report *Report, tsStructs map[string]StructDefinition, colliding map[string]bool) []byte {
	var buf bytes.Buffer
	buf.WriteString("// ⚠️ DO NOT EDIT — Auto-generated by nexssp/ops\n")
	singleFetcher := report != nil && report.APIClientConfig != nil && report.APIClientConfig.Transport == "single-fetcher"
	if singleFetcher {
		buf.WriteString("import { _fetcher, resolvePath, resolvePathOnly, resolvePathUnencoded, resolvePathOnlyUnencoded } from './client';\n")
	} else {
		buf.WriteString("import { _fetcher, _fetcherBlob, _fetcherMultipart, resolvePath, resolvePathOnly } from './client';\n")
	}
	if hasEmptyRequestContract(report) {
		buf.WriteString("import type { EmptyStruct } from './client';\n")
	}
	buf.WriteString("import * as Types from './types';\n\n")

	fieldFields := configuredFields(report, true)
	endpointFields := configuredFields(report, false)
	fmt.Fprintf(&buf, "export interface FieldMeta { %s }\n", metadataInterfaceFields(fieldFields, true))
	fmt.Fprintf(&buf, "export interface EndpointMeta { %s }\n", metadataInterfaceFields(endpointFields, false))
	buf.WriteString("export const endpointMeta: Record<string, EndpointMeta> = {\n")
	for _, act := range report.Actions {
		if act.Scope != "public" || act.Path == "" {
			continue
		}
		mName := SDKMethodName(act)
		meta := generatedEndpointMeta{
			Name:                act.Name,
			MethodName:          mName,
			Description:         act.Description,
			Node:                act.Node,
			Method:              act.Method,
			Path:                act.Path,
			ReqType:             generatedRequestTypeName(act, report.Structs),
			ResType:             act.ResTypeName,
			RequiresAuth:        act.RequiresAuth,
			RequiredRoles:       nonNilStrings(act.Roles),
			RequiredPermissions: nonNilStrings(act.Permissions),
			RequiredFeatures:    nonNilStrings(act.Features),
			Tags:                nonNilStrings(act.Tags),
			Fields:              generatedFieldMetas(act.ReqFields),
			ReqFields:           generatedFieldMetas(act.ReqFields),
			ResFields:           generatedFieldMetas(act.ResFields),
			RetryMax:            act.RetryMax,
			TimeoutMs:           int64(act.Timeout / time.Millisecond),
			ConcurrencyLimit:    act.ConcurrencyLimit,
			RateLimit:           act.RateLimit,
			CacheTtlMs:          int64(act.CacheTTL / time.Millisecond),
			Idempotent:          act.Idempotent,
			Deduplicated:        act.Deduplicated,
			Coalesced:           act.Coalesced,
			SuccessStatus:       act.SuccessStatus,
			Streaming:           act.Streaming,
			Raw:                 act.Raw,
			Multipart:           act.Multipart,
			Blob:                act.BlobResponse,
		}
		var metaJSON []byte
		if len(endpointFields) == 0 {
			metaJSON, _ = json.Marshal(meta)
		} else {
			selected := selectMetadata(meta, endpointFields)
			filterFieldMetadata(selected, report.APIClientConfig)
			metaJSON, _ = json.Marshal(selected)
		}
		fmt.Fprintf(&buf, "  %s: %s,\n", mName, string(metaJSON))
	}
	buf.WriteString("};\n\nexport const api = {\n")

	for _, act := range report.Actions {
		if act.Scope != "public" || act.Path == "" {
			continue
		}
		if act.Streaming || (act.Raw && !act.BlobResponse) {
			continue
		}

		emitEndpointMethodConfigured(&buf, act, tsStructs, report.Structs, colliding, report.APIClientConfig)
	}

	buf.WriteString("};\n")
	if config := report.APIClientConfig; config != nil {
		if config.FacadeExportName != "" {
			fmt.Fprintf(&buf, "\nexport { api as %s };\n", config.FacadeExportName)
		}
		if config.FactoryExportName != "" {
			fmt.Fprintf(&buf, "export const %s = () => api;\n", config.FactoryExportName)
		}
	}
	return buf.Bytes()
}

func configuredFields(report *Report, field bool) []string {
	if report == nil || report.APIClientConfig == nil {
		return nil
	}
	if field {
		return report.APIClientConfig.FieldMetadataFields
	}
	return report.APIClientConfig.EndpointMetadataFields
}

func metadataInterfaceFields(fields []string, field bool) string {
	if len(fields) == 0 {
		if field {
			fields = []string{"key", "type", "required", "label", "nullable", "validation", "raw_tags", "multipart"}
		} else {
			fields = []string{"name", "methodName", "description", "method", "path", "reqType", "resType", "requiresAuth", "requiredRoles", "requiredPermissions", "requiredFeatures", "tags", "node", "fields", "resFields", "retryMax", "timeoutMs", "concurrencyLimit", "rateLimit", "cacheTtlMs", "idempotent", "deduplicated", "coalesced", "successStatus", "streaming", "raw", "multipart", "blob", "reqFields"}
		}
	}
	var out []string
	for _, f := range fields {
		typ := "unknown"
		if field {
			switch f {
			case "key", "type", "label", "validation", "raw_tags":
				typ = "string"
			case "required", "nullable", "multipart":
				typ = "boolean"
			}
		} else {
			switch f {
			case "name", "methodName", "description", "method", "path", "reqType", "resType", "rateLimit":
				typ = "string"
			case "requiresAuth", "idempotent", "deduplicated", "coalesced", "streaming", "raw", "multipart", "blob":
				typ = "boolean"
			case "requiredRoles", "requiredPermissions", "requiredFeatures", "tags":
				typ = "string[]"
			case "fields", "reqFields", "resFields":
				typ = "FieldMeta[]"
			case "node":
				typ = "string"
			default:
				typ = "number"
			}
		}
		optional := ""
		if f == "nullable" || f == "validation" || f == "raw_tags" || f == "multipart" || f == "node" || f == "concurrencyLimit" || f == "rateLimit" || f == "cacheTtlMs" || f == "successStatus" || f == "streaming" || f == "raw" || f == "blob" {
			optional = "?"
		}
		out = append(out, f+optional+": "+typ+";")
	}
	return strings.Join(out, " ")
}

func filterFieldMetadata(selected map[string]any, config *APIClientConfig) {
	if config == nil || len(config.FieldMetadataFields) == 0 {
		return
	}
	allowed := map[string]bool{}
	for _, key := range config.FieldMetadataFields {
		allowed[key] = true
	}
	for _, fieldName := range []string{"fields", "reqFields", "resFields"} {
		rows, ok := selected[fieldName].([]any)
		if !ok {
			continue
		}
		for i, row := range rows {
			item, ok := row.(map[string]any)
			if !ok {
				continue
			}
			filtered := map[string]any{}
			for key, value := range item {
				if allowed[key] {
					filtered[key] = value
				}
			}
			rows[i] = filtered
		}
		selected[fieldName] = rows
	}
}

func selectMetadata(meta generatedEndpointMeta, fields []string) map[string]any {
	if len(fields) == 0 {
		b, _ := json.Marshal(meta)
		var result map[string]any
		_ = json.Unmarshal(b, &result)
		return result
	}
	b, _ := json.Marshal(meta)
	var all map[string]any
	_ = json.Unmarshal(b, &all)
	result := make(map[string]any, len(fields))
	for _, f := range fields {
		if v, ok := all[f]; ok {
			result[f] = v
		}
	}
	return result
}

type generatedFieldMeta struct {
	Key        string `json:"key"`
	Type       string `json:"type"`
	Required   bool   `json:"required"`
	Label      string `json:"label"`
	Nullable   bool   `json:"nullable,omitempty"`
	Validation string `json:"validation,omitempty"`
	RawTags    string `json:"raw_tags,omitempty"`
	Multipart  bool   `json:"multipart,omitempty"`
}

type generatedEndpointMeta struct {
	Name                string               `json:"name"`
	MethodName          string               `json:"methodName"`
	Description         string               `json:"description"`
	Method              string               `json:"method"`
	Path                string               `json:"path"`
	ReqType             string               `json:"reqType"`
	ResType             string               `json:"resType"`
	RequiresAuth        bool                 `json:"requiresAuth"`
	RequiredRoles       []string             `json:"requiredRoles"`
	RequiredPermissions []string             `json:"requiredPermissions"`
	RequiredFeatures    []string             `json:"requiredFeatures"`
	Tags                []string             `json:"tags"`
	Fields              []generatedFieldMeta `json:"fields"`
	ReqFields           []generatedFieldMeta `json:"reqFields"`
	ResFields           []generatedFieldMeta `json:"resFields"`
	RetryMax            int                  `json:"retryMax"`
	TimeoutMs           int64                `json:"timeoutMs"`
	ConcurrencyLimit    int32                `json:"concurrencyLimit"`
	RateLimit           string               `json:"rateLimit"`
	CacheTtlMs          int64                `json:"cacheTtlMs"`
	Idempotent          bool                 `json:"idempotent"`
	Node                string               `json:"node"`
	Deduplicated        bool                 `json:"deduplicated"`
	Coalesced           bool                 `json:"coalesced"`
	SuccessStatus       int                  `json:"successStatus,omitempty"`
	Streaming           bool                 `json:"streaming"`
	Raw                 bool                 `json:"raw"`
	Multipart           bool                 `json:"multipart,omitempty"`
	Blob                bool                 `json:"blob,omitempty"`
}

func generatedFieldMetasConfigured(fields []FieldContract, cfg *APIClientConfig) []generatedFieldMeta {
	metas := generatedFieldMetas(fields)
	if cfg == nil || len(cfg.FieldMetadataFields) == 0 {
		return metas
	}
	allowed := map[string]bool{}
	for _, n := range cfg.FieldMetadataFields {
		allowed[n] = true
	}
	out := make([]generatedFieldMeta, 0, len(metas))
	for _, m := range metas {
		b, _ := json.Marshal(m)
		var all map[string]any
		_ = json.Unmarshal(b, &all)
		selected := map[string]any{}
		for k, v := range all {
			if allowed[k] {
				selected[k] = v
			}
		}
		raw, _ := json.Marshal(selected)
		var clean generatedFieldMeta
		_ = json.Unmarshal(raw, &clean)
		out = append(out, clean)
	}
	return out
}

func generatedFieldMetas(fields []FieldContract) []generatedFieldMeta {
	metadata := make([]generatedFieldMeta, 0, len(fields))
	for _, field := range fields {
		label := field.Name
		if label == "" {
			label = field.Key
		}
		metadata = append(metadata, generatedFieldMeta{
			Key:        field.Key,
			Type:       field.Type,
			Required:   field.Required,
			Label:      label,
			Nullable:   field.Nullable,
			Validation: field.Validation,
			RawTags:    field.RawTags,
			Multipart:  field.Multipart,
		})
	}
	return metadata
}

func nonNilStrings(values []string) []string {
	return append([]string{}, values...)
}

// pathResolverFor returns the client-side URL resolver that matches the HTTP
// method. GET and DELETE carry their payload in the query string; POST, PUT,
// and PATCH carry it in the body. Using resolvePath for a body method would
// duplicate every field into both the URL and the JSON body.
func pathResolverFor(method string) string {
	switch method {
	case "GET", "DELETE":
		return "resolvePath"
	default:
		return "resolvePathOnly"
	}
}

func queryRequestIsOptional(act ActionContract) bool {
	if act.Method != "GET" && act.Method != "DELETE" {
		return false
	}
	for _, field := range act.ReqFields {
		if field.Required {
			return false
		}
	}
	return true
}

func isEmptyRequestContract(act ActionContract, rawStructs map[string]StructDefinition) bool {
	if act.FlowSchemaDriven && act.ReqSchemaName == "" {
		return false
	}
	if act.ReqTypeName == "struct{}" || act.ReqTypeName == "EmptyStruct" {
		return true
	}
	definition, ok := resolveActionStruct(act, true, rawStructs)
	return ok && len(definition.Fields) == 0
}

func hasEmptyRequestContract(report *Report) bool {
	if report == nil {
		return false
	}
	for _, action := range report.Actions {
		if action.Scope == "public" && action.Path != "" && isEmptyRequestContract(action, report.Structs) {
			return true
		}
	}
	return false
}

func generatedRequestTypeName(act ActionContract, rawStructs map[string]StructDefinition) string {
	if isEmptyRequestContract(act, rawStructs) {
		return "EmptyStruct"
	}
	return act.ReqTypeName
}

func emptyRequestArgumentType(path string) (string, bool) {
	params := pathParameterNames(path)
	if len(params) == 0 {
		return "EmptyStruct", false
	}
	fields := make([]string, 0, len(params))
	for _, name := range params {
		fields = append(fields, name+": string | number")
	}
	return "{ " + strings.Join(fields, "; ") + " }", true
}

func pathParameterNames(path string) []string {
	var names []string
	seen := make(map[string]struct{})
	for offset := 0; offset < len(path); {
		start := strings.IndexByte(path[offset:], '{')
		if start < 0 {
			break
		}
		start += offset + 1
		end := strings.IndexByte(path[start:], '}')
		if end < 0 {
			break
		}
		name := strings.TrimSpace(strings.TrimSuffix(path[start:start+end], "..."))
		if name != "" {
			if _, ok := seen[name]; !ok {
				seen[name] = struct{}{}
				names = append(names, name)
			}
		}
		offset = start + end + 1
	}
	return names
}

func emitEndpointMethod(buf *bytes.Buffer, act ActionContract, tsStructs, rawStructs map[string]StructDefinition, colliding map[string]bool) {
	emitEndpointMethodConfigured(buf, act, tsStructs, rawStructs, colliding, nil)
}

func emitEndpointMethodConfigured(
	buf *bytes.Buffer,
	act ActionContract,
	tsStructs, rawStructs map[string]StructDefinition,
	colliding map[string]bool,
	config *APIClientConfig,
) {
	mName := SDKMethodName(act)
	resolver := pathResolverFor(act.Method)
	if config != nil && config.PathParameterEncoding == "none" {
		resolver += "Unencoded"
	}

	// Blob response short-circuits everything else.
	if act.BlobResponse {
		blobFetcher := "_fetcherBlob"
		blobTypeArg, blobMode := "", ""
		if config != nil && config.Transport == "single-fetcher" {
			blobFetcher, blobTypeArg, blobMode = "_fetcher", "<Blob>", ", responseMode: 'blob'"
		}
		reqT := formatTSNamespaceType(resolveActionTypeTS(act, true, tsStructs, rawStructs, colliding), tsStructs)
		emptyRequest := isEmptyRequestContract(act, rawStructs)
		hasPathParams := false
		if emptyRequest {
			reqT, hasPathParams = emptyRequestArgumentType(act.Path)
		} else if reqT == "void" && len(pathParameterNames(act.Path)) > 0 {
			reqT, hasPathParams = emptyRequestArgumentType(act.Path)
			emptyRequest = true
		}
		valCheck := ""
		if sDef, ok := resolveActionStruct(act, true, rawStructs); ok && len(sDef.Fields) > 0 {
			valCheck = fmt.Sprintf("\n    Types.%sSchema.parse(req ?? {});", targetTSName(sDef, colliding))
		}
		if reqT == "void" {
			fmt.Fprintf(buf,
				"  %s: (): Promise<Blob> => {\n    return %s%s({ method: '%s', path: '%s'%s });\n  },\n\n",
				mName, blobFetcher, blobTypeArg, act.Method, act.Path, blobMode,
			)
			return
		}
		if act.Method == "GET" || act.Method == "DELETE" {
			optional := ""
			if requestIsOptional(act, emptyRequest, hasPathParams) {
				optional = "?"
			}
			fmt.Fprintf(buf,
				"  %s: (req%s: %s): Promise<Blob> => {%s\n    return %s%s({ method: '%s', path: %s('%s', req)%s });\n  },\n\n",
				mName, optional, reqT, valCheck, blobFetcher, blobTypeArg, act.Method, resolver, act.Path, blobMode,
			)
			return
		}
		requestArgument := "req: " + reqT
		if requestIsOptional(act, emptyRequest, hasPathParams) {
			requestArgument = "req?: " + reqT
		}
		fmt.Fprintf(buf,
			"  %s: (%s): Promise<Blob> => {%s\n    return %s%s({ method: '%s', path: %s('%s', req), body: req%s });\n  },\n\n",
			mName, requestArgument, valCheck, blobFetcher, blobTypeArg, act.Method, resolver, act.Path, blobMode,
		)
		return
	}

	// Multipart.
	if act.Multipart {
		reqT := formatTSNamespaceType(resolveActionTypeTS(act, true, tsStructs, rawStructs, colliding), tsStructs)
		resT := formatTSNamespaceType(resolveActionTypeTS(act, false, tsStructs, rawStructs, colliding), tsStructs)

		sDef, hasStruct := resolveActionStruct(act, true, rawStructs)
		tsReqT := lastSegment(act.ReqTypeName)
		if hasStruct {
			tsReqT = targetTSName(sDef, colliding)
		}

		fmt.Fprintf(buf, "  %s: (req: %s): Promise<%s> => {\n", mName, reqT, resT)
		if act.ValidateMultipartRequest && hasStruct && len(sDef.Fields) > 0 {
			fmt.Fprintf(buf, "    Types.%sSchema.parse(req);\n", targetTSName(sDef, colliding))
		}
		fmt.Fprintf(buf, "    const fd = new FormData();\n")

		if hasStruct {
			for _, f := range sDef.Fields {
				if f.Multipart {
					if f.Required {
						fmt.Fprintf(buf, "    fd.append(%q, req.%s as unknown as Blob);\n", f.Key, f.Key)
					} else {
						fmt.Fprintf(buf, "    if (req.%s != null) fd.append(%q, req.%s as unknown as Blob);\n", f.Key, f.Key, f.Key)
					}
				} else {
					fmt.Fprintf(buf, "    fd.append(%q, String(req.%s ?? ''));\n", f.Key, f.Key)
				}
			}
		}
		_ = tsReqT

		multipartFetcher := "_fetcherMultipart"
		if config != nil && config.Transport == "single-fetcher" {
			multipartFetcher = "_fetcher"
		}
		fmt.Fprintf(buf, "    return %s({ method: '%s', path: %s('%s', req), body: fd });\n", multipartFetcher, act.Method, resolver, act.Path)
		fmt.Fprintf(buf, "  },\n\n")
		return
	}

	// Plain JSON — the existing path.
	rawReqT := resolveActionTypeTS(act, true, tsStructs, rawStructs, colliding)
	rawResT := resolveActionTypeTS(act, false, tsStructs, rawStructs, colliding)

	reqT := formatTSNamespaceType(rawReqT, tsStructs)
	resT := formatTSNamespaceType(rawResT, tsStructs)
	emptyRequest := isEmptyRequestContract(act, rawStructs)
	hasPathParams := false
	if emptyRequest {
		reqT, hasPathParams = emptyRequestArgumentType(act.Path)
	} else if reqT == "void" && len(pathParameterNames(act.Path)) > 0 {
		reqT, hasPathParams = emptyRequestArgumentType(act.Path)
		emptyRequest = true
	}

	valCheck := ""
	if sDef, ok := resolveActionStruct(act, true, rawStructs); ok && len(sDef.Fields) > 0 {
		valCheck = fmt.Sprintf("\n    Types.%sSchema.parse(req ?? {});", targetTSName(sDef, colliding))
	}

	if reqT == "void" {
		fmt.Fprintf(buf,
			"  %s: (): Promise<%s> => {\n    return _fetcher({ method: '%s', path: '%s' });\n  },\n\n",
			mName, resT, act.Method, act.Path,
		)
		return
	}

	if act.Method == "GET" || act.Method == "DELETE" {
		optional := ""
		if requestIsOptional(act, emptyRequest, hasPathParams) {
			optional = "?"
		}
		fmt.Fprintf(buf,
			"  %s: (req%s: %s): Promise<%s> => {%s\n    return _fetcher({ method: '%s', path: %s('%s', req) });\n  },\n\n",
			mName, optional, reqT, resT, valCheck, act.Method, resolver, act.Path,
		)
		return
	}

	requestArgument := "req: " + reqT
	if emptyRequest && !hasPathParams {
		requestArgument = "req?: " + reqT
	}
	fmt.Fprintf(buf,
		"  %s: (%s): Promise<%s> => {%s\n    return _fetcher({ method: '%s', path: %s('%s', req), body: req });\n  },\n\n",
		mName, requestArgument, resT, valCheck, act.Method, resolver, act.Path,
	)
}

func formatTSNamespaceType(t string, tsStructs map[string]StructDefinition) string {
	if t == "" || t == "void" || t == "unknown" {
		return "void"
	}
	switch t {
	case "string", "number", "boolean", "IsoDateString":
		return t
	}
	if strings.HasSuffix(t, "[]") {
		return formatTSNamespaceType(strings.TrimSuffix(t, "[]"), tsStructs) + "[]"
	}
	if strings.HasPrefix(t, "Record<") || strings.Contains(t, "|") {
		return t
	}
	if sDef, ok := tsStructs[t]; ok {
		// Structs with zero fields are filtered out of types.ts. Referring
		// to Types.X for them produces a dangling reference in the emitted
		// endpoint methods. Treat as void so the method has no typed arg.
		if len(sDef.Fields) == 0 {
			return "void"
		}
		return "Types." + t
	}
	return "Record<string, unknown>"
}

func requestIsOptional(act ActionContract, emptyRequest, hasPathParams bool) bool {
	if act.RequestOptional != nil {
		return *act.RequestOptional
	}
	return (emptyRequest && !hasPathParams) || (!emptyRequest && queryRequestIsOptional(act))
}
